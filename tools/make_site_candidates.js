// Run from the repo root: node tools/make_site_candidates.js > src/site-candidates.js
'use strict';
const { inflateSync } = require('node:zlib');
const Astronomy = require('astronomy-engine');
const engine = require('../src/engine.js')(Astronomy);
const terrain = require('../src/terrain.js');
const { regions } = require('./artemis_regions.json');
const original = require('./artemis_spots.json');
global.window = {};
require('../src/terrain-grid.js');
require('../src/horizon-data.js');
require('../src/plugins/rules.js');

const grid = terrain.loadNode(window.MW_TERRAIN_GRID, inflateSync);
const horizons = window.MW_HORIZONS;
const { slopeOf } = window.MW_RULES;
const rad = Math.PI / 180;
const round = (value, digits) => Number(value.toFixed(digits));
const radiusKm = engine.MOON_RADIUS_KM;
const dates = Array.from({ length: 365 * 12 }, (_, i) => new Date(Date.UTC(2027, 0, 1, i * 2)));

function pointAt(center, eastKm, northKm) {
  const angle = Math.hypot(eastKm, northKm) / radiusKm;
  const bearing = Math.atan2(eastKm, northKm);
  const lat = center.lat * rad;
  const nextLat = Math.asin(Math.sin(lat) * Math.cos(angle) + Math.cos(lat) * Math.sin(angle) * Math.cos(bearing));
  const dLon = Math.atan2(Math.sin(bearing) * Math.sin(angle) * Math.cos(lat), Math.cos(angle) - Math.sin(lat) * Math.sin(nextLat));
  return { lat: round(nextLat / rad, 4), lon: round((center.lon + dLon / rad + 360) % 360, 4) % 360 };
}

function fractions({ lat, lon }, profile) {
  function visible(body) {
    const index = body.az * profile.length / 360;
    const i = Math.floor(index) % profile.length;
    const t = index - Math.floor(index);
    return body.el > profile[i] * (1 - t) + profile[(i + 1) % profile.length] * t;
  }
  let sun = 0, earth = 0, both = 0;
  for (const date of dates) {
    const sky = engine.skyAt(date, lat, lon);
    const s = visible(sky.sun), e = visible(sky.earth);
    sun += Number(s);
    earth += Number(e);
    both += Number(s && e);
  }
  return { sun: sun / dates.length, earth: earth / dates.length, both: both / dates.length };
}

const result = regions.map(region => {
  const best = original[region.id];
  const stored = horizons.sites[region.id];
  const point = { lat: best.lat, lon: best.lon };
  const sites = [{
    ...point, distanceKm: best.distanceKm, slope: best.slopeDeg,
    resM: stored.resM || horizons.meta.resolutionM, original: true,
    ...fractions(point, stored.values)
  }];
  for (let east = -5; east <= 5; east++) {
    for (let north = -5; north <= 5; north++) {
      const distanceKm = Math.hypot(east, north);
      if (distanceKm > 5) continue;
      const point = pointAt(region, east, north);
      const dLat = (point.lat - best.lat) * rad;
      const dLon = (point.lon - best.lon) * rad;
      const distanceToBest = 2 * radiusKm * Math.asin(Math.sqrt(Math.sin(dLat / 2) ** 2 +
        Math.cos(point.lat * rad) * Math.cos(best.lat * rad) * Math.sin(dLon / 2) ** 2));
      if (distanceToBest < 0.5 || !grid.covers(point.lat)) continue;
      const slope = slopeOf({ ...point, siteId: 'custom' }, { terrainGrid: grid });
      const skyline = grid.profile(point.lat, point.lon);
      if (!slope || !skyline) continue;
      sites.push({ ...point, distanceKm: round(distanceKm, 2), slope: slope.deg, resM: slope.resM,
        ...fractions(point, skyline.values) });
    }
  }
  return { id: region.id, name: region.name, sites };
});

console.log('// Generated by tools/make_site_candidates.js from the bundled NASA LOLA grids.');
console.log('window.MW_SITE_CANDIDATES = ' + JSON.stringify(result) + ';');
